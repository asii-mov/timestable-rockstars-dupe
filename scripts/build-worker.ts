/**
 * Bundles the static `dist/` build into a single Cloudflare Worker script
 * (dist-worker/worker.js) that serves every file from memory.
 *
 * The whole site is ~90 KB, so embedding it keeps deployment to a single API
 * call — no separate asset upload step. Cloudflare compresses text responses
 * at the edge automatically.
 *
 * Run with: bun scripts/build-worker.ts (after `vite build`).
 */
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const DIST = 'dist';
const OUT_DIR = 'dist-worker';

const TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webmanifest': 'application/manifest+json',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
};
const BINARY = new Set(['.png']);

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

function cacheControl(path: string): string {
  // Vite content-hashes everything under /assets/, so it never changes.
  if (path.startsWith('/assets/')) return 'public, max-age=31536000, immutable';
  // The page and service worker must always revalidate so updates ship.
  if (path === '/index.html' || path === '/sw.js') return 'no-cache';
  return 'public, max-age=86400';
}

const files: Record<string, { type: string; cache: string; body: string; b64: boolean }> = {};
for (const file of walk(DIST)) {
  const path = '/' + relative(DIST, file).split('\\').join('/');
  const ext = extname(file);
  const b64 = BINARY.has(ext);
  const buf = readFileSync(file);
  files[path] = {
    type: TYPES[ext] ?? 'application/octet-stream',
    cache: cacheControl(path),
    body: b64 ? buf.toString('base64') : buf.toString('utf8'),
    b64,
  };
}

const worker = `// Generated by scripts/build-worker.ts — do not edit.
const FILES = ${JSON.stringify(files)};
const decoded = new Map();
function body(f, path) {
  if (!f.b64) return f.body;
  let bytes = decoded.get(path);
  if (!bytes) {
    bytes = Uint8Array.from(atob(f.body), (c) => c.charCodeAt(0));
    decoded.set(path, bytes);
  }
  return bytes;
}
const SECURITY = {
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'strict-origin-when-cross-origin',
  'x-frame-options': 'DENY',
};
export default {
  async fetch(request) {
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed', { status: 405, headers: { allow: 'GET, HEAD' } });
    }
    const url = new URL(request.url);
    let path = url.pathname;
    if (path.endsWith('/')) path += 'index.html';
    let f = FILES[path];
    let status = 200;
    if (!f) {
      // Unknown page navigations get the app shell; missing assets get a 404.
      const accept = request.headers.get('accept') || '';
      if (accept.includes('text/html')) { path = '/index.html'; f = FILES[path]; }
      else return new Response('Not found', { status: 404, headers: SECURITY });
    }
    const etag = '"' + ${JSON.stringify(Date.now().toString(36))} + '"';
    const headers = { ...SECURITY, 'content-type': f.type, 'cache-control': f.cache, etag };
    if (request.headers.get('if-none-match') === etag) return new Response(null, { status: 304, headers });
    return new Response(request.method === 'HEAD' ? null : body(f, path), { status, headers });
  },
};
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'worker.js'), worker);
console.log(`Wrote ${OUT_DIR}/worker.js with ${Object.keys(files).length} files (${(worker.length / 1024).toFixed(1)} KB)`);
